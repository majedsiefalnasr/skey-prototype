import {test, expect} from '@playwright/test'

const canvas = page => page.locator('#notifications-list-canvas')

async function openNotifications(page) {
  await page.goto('/help-screens/notifications')
  if (await page.locator('#kit-hide').isVisible()) await page.locator('#kit-hide').click()
  await expect(canvas(page).locator('[data-notification-action="pin"]')).toHaveCount(8)
  await expect(canvas(page).locator('[data-notification-action="read"]')).toHaveCount(1)
  await expect(page.locator('.notifications-list-view h1')).toHaveText('Notifications')
}

test('notifications keep their list interactive after the invoice shell updates', async ({page}) => {
  await openNotifications(page)
  await expect(canvas(page).locator('thead th')).toContainText(['', 'Subject', 'Source', ''])
  await expect(canvas(page).locator('td.data-row-actions-cell').first()).toHaveCSS('position', 'sticky')
  await expect(canvas(page).locator('th.data-row-actions-cell')).toHaveText('')
  const readAction = canvas(page).locator('[data-notification-action="pin"]').first()
  await expect(readAction.locator('svg')).toHaveCount(1)
  await expect(readAction.locator('..')).toHaveCSS('justify-content', 'flex-end')
  await expect(readAction.locator('..')).toHaveCSS('display', 'flex')
  for (const direction of ['ltr', 'rtl']) {
    await canvas(page).evaluate((element, dir) => { element.dir = dir }, direction)
    await expect.poll(() => readAction.evaluate(button => {
      const cell = button.closest('td')
      const pin = cell.querySelector('[data-notification-action="pin"]')
      const rect = cell.getBoundingClientRect()
      const action = pin.getBoundingClientRect()
      const style = getComputedStyle(cell)
      return Math.abs(style.direction === 'rtl'
        ? action.left - rect.left - parseFloat(style.paddingLeft)
        : rect.right - action.right - parseFloat(style.paddingRight))
    })).toBeLessThan(2)
  }
  await canvas(page).evaluate(element => { element.removeAttribute('dir') })
  const subject = canvas(page).locator('[data-list-open-record]').first()
  await expect(subject).toHaveCSS('color', await subject.evaluate(el => { const probe = document.createElement('span'); probe.style.color = 'var(--accent)'; el.append(probe); const color = getComputedStyle(probe).color; probe.remove(); return color }))
  await expect(subject.locator('[aria-hidden="true"]')).toHaveCount(0)
  await expect(canvas(page).locator('th.data-row-select-cell')).toHaveCSS('width', '42px')
  await page.keyboard.press('Tab')
  await readAction.focus()
  await expect(page.locator('#notification-action-tooltip')).toBeVisible()
  await expect(page.locator('#notification-action-tooltip')).toHaveText('Pin notification')
  await canvas(page).getByRole('button', {name: 'Pin notification'}).first().click()
  await expect(canvas(page).getByRole('button', {name: 'Unpin notification'})).toHaveCount(1)
  await canvas(page).locator('[data-list-open-record]').first().click()
  await expect(page.locator('#notification-modal')).toBeVisible()
  await expect(page.locator('#notification-modal-actions').getByRole('button', {name: 'Mark as unread'})).toBeVisible()
  await expect(page.locator('#notification-modal-actions > span')).toHaveCSS('justify-content', 'flex-end')
  await expect(canvas(page).locator('[data-notification-action="read"]')).toHaveCount(2)
  await page.locator('#notification-modal-actions').getByRole('button', {name: 'Mark as unread'}).click()
  await expect(page.locator('#notification-modal-actions').getByRole('button', {name: 'Mark as unread'})).toHaveCount(0)
  await expect(page.locator('#notification-modal-actions').getByRole('button', {name: 'Unpin notification'})).toBeVisible()
  await expect(canvas(page).locator('[data-notification-action="read"]')).toHaveCount(1)
  await page.locator('#notification-modal-close-btn').click()
  await expect(canvas(page).locator('[data-list-open-record]')).toHaveCount(8)
  await page.reload()
  await expect(canvas(page).getByRole('button', {name: 'Unpin notification'})).toHaveCount(1)
  await canvas(page).locator('details').filter({has: page.locator('[data-list-view="cards"]')}).locator('summary').click()
  await canvas(page).locator('[data-list-view="cards"]').click()
  await expect(canvas(page).locator('.data-record-card-notification')).toHaveCount(8)
  await expect(canvas(page).locator('.data-record-card-notification .badge')).toHaveCount(0)
  await expect(canvas(page).locator('.data-record-card-notification strong [aria-hidden]')).toHaveCount(0)
  const cardAction = canvas(page).getByRole('button', {name: 'Unpin notification'})
  await expect(cardAction.locator('..')).toHaveCSS('justify-content', 'flex-end')
  await cardAction.hover()
  await expect(page.locator('#notification-action-tooltip')).toBeVisible()
  await expect(canvas(page).locator('.data-record-card-notification header [data-notification-action]')).toHaveCount(9)
  await expect(canvas(page).locator('.data-record-card-notification footer')).toHaveCount(0)
  await expect(cardAction).not.toHaveClass(/accent-soft/)
})


test('bulk notification selection persists read state in table and cards without changing pins', async ({page}) => {
  await openNotifications(page)
  const rows = canvas(page).locator('tbody tr[data-list-row-key]')
  const pinnedId = await rows.nth(3).getAttribute('data-list-row-key')
  await rows.nth(3).locator('[data-notification-action="pin"]').click()
  await rows.first().locator('[data-list-open-record]').click()
  await page.locator('#notification-modal-close-btn').click()
  await canvas(page).locator('[data-list-row-select]').nth(0).check()
  await canvas(page).locator('[data-list-row-select]').nth(1).check()
  await expect(canvas(page).locator('.data-selection-count')).toContainText('2')
  await expect(canvas(page).locator('[data-list-select-all]')).toHaveJSProperty('indeterminate', true)
  await expect(canvas(page).locator('[data-list-action="delete"], [data-list-action="modify"]')).toHaveCount(0)
  await expect(canvas(page).locator('[data-list-action="mark-read"]')).toHaveCount(0)
  await canvas(page).locator('[data-list-action="mark-unread"]').click()
  await expect(canvas(page).locator('.data-selection-toolbar')).toHaveCount(0)
  await expect(rows.first()).toHaveAttribute('data-list-row-key', pinnedId)
  await page.reload()
  await expect(rows.first().getByRole('button', {name: 'Mark as unread', exact: true})).toHaveCount(0)
  await canvas(page).locator('details').filter({has: page.locator('[data-list-view="cards"]')}).locator('summary').click()
  await canvas(page).locator('[data-list-view="cards"]').click()
  await canvas(page).locator('.data-record-card-notification').first().locator('[data-list-open-record]').click()
  await page.locator('#notification-modal-close-btn').click()
  await canvas(page).locator('[data-list-row-select]').nth(0).check()
  await canvas(page).locator('[data-list-row-select]').nth(1).check()
  await canvas(page).locator('[data-list-action="mark-unread"]').click()
  await page.reload()
  await canvas(page).locator('details').filter({has: page.locator('[data-list-view="cards"]')}).locator('summary').click()
  await canvas(page).locator('[data-list-view="cards"]').click()
  await expect(canvas(page).locator('.data-record-card-notification').first()).toHaveAttribute('data-list-row-key', pinnedId)
  await expect(canvas(page).locator('.data-record-card-notification').first().getByRole('button', {name: 'Mark as unread', exact: true})).toHaveCount(0)
  await expect(canvas(page).locator('.data-record-card-notification').first().getByRole('button', {name: 'Unpin notification'})).toBeVisible()
  await canvas(page).locator('[data-list-row-select]').first().check()
  await canvas(page).getByRole('button', {name: 'Clear selection'}).click()
  await expect(canvas(page).locator('.data-selection-toolbar')).toHaveCount(0)
})

test('select all targets only matching unread notifications', async ({page}) => {
  await openNotifications(page)
  await canvas(page).locator('#notifications-page-unread-only').check()
  const count = await canvas(page).locator('[data-list-row-select]').count()
  await canvas(page).getByRole('checkbox', {name: 'Select all matching notifications'}).check()
  await expect(canvas(page).locator('.data-selection-count')).toContainText(String(count))
  await expect(canvas(page).locator('[data-list-action="mark-read"]')).toHaveCount(0)
  await expect(canvas(page).locator('[data-list-action="mark-unread"]')).toHaveCount(0)
  await expect(canvas(page).locator('[data-list-row-select]')).toHaveCount(count)
  await page.reload()
  await expect(canvas(page).getByRole('button', {name: 'Mark as unread', exact: true})).toHaveCount(1)
})

test('notification field menu offers only Subject and Source', async ({page}) => {
  await openNotifications(page)
  const choices = canvas(page).locator('[data-list-add-filter]')
  await expect(choices).toHaveCount(2)
  await expect(choices).toHaveText(['Subject', 'Source'])
  await expect(canvas(page).locator('[data-list-add-filter="who"], [data-list-add-filter="type"]')).toHaveCount(0)
})

test('pin moves a notification first and unpin restores its original position', async ({page}) => {
  await openNotifications(page)
  const rows = canvas(page).locator('tbody tr[data-list-row-key]')
  const original = await rows.evaluateAll(elements => elements.map(el => el.dataset.listRowKey))
  const target = original[4]
  await canvas(page).locator(`[data-list-row-key="${target}"] [data-notification-action="pin"]`).click()
  await expect(rows.first()).toHaveAttribute('data-list-row-key', target)
  await page.reload()
  await expect(rows.first()).toHaveAttribute('data-list-row-key', target)
  await canvas(page).getByRole('button', {name: 'Unpin notification'}).click()
  await expect.poll(() => rows.evaluateAll(elements => elements.map(el => el.dataset.listRowKey))).toEqual(original)
})

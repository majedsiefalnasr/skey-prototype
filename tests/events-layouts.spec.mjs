test('today uses only a day-number marker in Month, Week, and Day', async ({page}, info) => {
  await go(page, info)
  const monthToday = page.locator('[data-date="2026-10-13"]')
  const monthOther = page.locator('[data-date="2026-10-14"]')
  const paint = el => ({background: getComputedStyle(el).backgroundColor, shadow: getComputedStyle(el).boxShadow})
  expect(await monthToday.evaluate(paint)).toEqual(await monthOther.evaluate(paint))
  const marker = await page.locator('[data-cal-select-day="2026-10-13"]').evaluate(el => getComputedStyle(el).backgroundColor)
  const chipBorder = await page.locator('[data-cal-item]').first().evaluate(el => getComputedStyle(el).borderInlineStartWidth)
  expect(chipBorder).toBe('0px')
  await capture(page, info, 'events-calendar-month.png')
  for (const mode of ['week', 'day']) {
    await page.locator(`[data-cal-modes] [data-value="${mode}"]`).click()
    const header = page.locator('[data-cal-column-date="2026-10-13"]')
    await expect(header.locator('.event-calendar-day-number')).toHaveText(info.project.use.rtl ? '١٣' : '13')
    expect(await header.locator('.event-calendar-day-number').evaluate(el => getComputedStyle(el).backgroundColor)).toBe(marker)
    expect(await header.evaluate(el => getComputedStyle(el).boxShadow)).toBe('none')
    const column = page.locator('[data-cal-timed-date="2026-10-13"]')
    expect(await column.evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgba(0, 0, 0, 0)')
    if (mode === 'week') {
      expect(await header.evaluate(paint)).toEqual(await page.locator('[data-cal-column-date="2026-10-14"]').evaluate(paint))
    } else {
      expect(await header.evaluate(el => getComputedStyle(el).backgroundColor)).toBe(await page.locator('[data-cal-day]').evaluate(el => getComputedStyle(el).backgroundColor))
    }
    await capture(page, info, `events-calendar-${mode}.png`)
  }
})

test('upcoming events stay available outside the chosen day and navigate the agenda', async ({page}, info) => {
  await go(page, info)
  await layout(page, 'agenda')
  const sidebar = page.locator('[data-event-sidebar]')
  await expect(sidebar.locator('[data-event-upcoming]')).toHaveCount(3)
  await sidebar.locator('[data-event-view-all]').click()
  expect(await sidebar.locator('[data-event-upcoming]').count()).toBeGreaterThan(3)
  await sidebar.locator('[data-event-view-all]').click()
  await expect(sidebar.locator('[data-event-upcoming]')).toHaveCount(3)
  await sidebar.locator('[data-event-upcoming]').first().click()
  await expect(page.locator('[data-cal-modes] [data-value="day"]')).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('[data-agenda-event]')).toHaveCount(1)
  await expect(page.locator('[data-agenda-event]')).toContainText('Monthly sales review')
  await expect(page.locator('[data-agenda-event]')).toBeInViewport()
  await expect(page.locator('#collab-panel')).toBeHidden()
})


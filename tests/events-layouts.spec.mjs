test('timezone selection keeps the displayed day, original wall time, and saved category', async ({page}, info) => {
  await go(page, info)
  await page.locator('[data-collab-new]').click()
  await page.locator('#event-title').fill('Midnight handover')
  await page.locator('#event-category').selectOption('company')
  await page.locator('#event-start').fill('2026-10-13T00:30')
  await page.locator('#event-end').fill('2026-10-13T01:30')
  await page.locator('#collab-panel [data-panel-save]').click()
  await layout(page, 'agenda')
  await row(page, 'Midnight handover').locator('[data-agenda-event]').click()
  await page.locator('[data-panel-close]').click()
  await page.locator('[data-display-zone]').selectOption('UTC')
  await expect(page.locator('[data-event-day="2026-10-12"]')).toHaveAttribute('aria-pressed', 'true')
  await expect(row(page, 'Midnight handover').locator('.event-time-column')).toContainText('21:30')
  await row(page, 'Midnight handover').locator('[data-agenda-event]').click()
  await page.locator('#collab-panel [data-panel-edit]').click()
  await expect(page.locator('#event-start')).toHaveValue('2026-10-13T00:30')
  await expect(page.locator('#event-timezone')).toHaveValue('Africa/Cairo')
  await expect(page.locator('#event-category')).toHaveValue('company')
  await page.locator('[data-panel-close]').click()
  await page.reload()
  await settle(page)
  await layout(page, 'agenda')
  await expect(row(page, 'Midnight handover')).toHaveClass(/event-category-company/)
})

test('location filters apply to both layouts and leave the sidebar free of event details', async ({page}, info) => {
  await go(page, info)
  await page.locator('[data-filter-menu] summary').click()
  await page.locator('[data-collab-add-filter="location"]').click()
  await page.locator('[data-collab-filter-value="location"]').fill('Cairo')
  await expect(page.locator('[data-cal-item]')).toHaveCount(1)
  await layout(page, 'agenda')
  await expect(page.locator('[data-agenda-event]')).toHaveCount(1)
  await expect(page.locator('[data-agenda-event]')).toContainText('Customer visit')
  await page.locator('[data-collab-editor-key="location"] summary').click()
  await page.locator('[data-collab-filter-value="location"]').fill('No matching location')
  await expect(page.locator('[data-agenda-event]')).toHaveCount(0)
  await expect(page.locator('[data-event-selected]')).toHaveCount(0)
  await page.locator('[data-clear-filters]').click()
  await expect(page.locator('[data-agenda-event]')).toHaveCount(4)
})

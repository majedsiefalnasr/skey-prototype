import {test, expect} from '@playwright/test'
import {settle} from './support/browser.mjs'

async function go(page, info) {
  await page.route('https://cdn.jsdelivr.net/**', route => route.abort())
  await page.goto('/help-screens/events')
  await page.locator('#simulate-loading').uncheck()
  await page.locator('#rtl').evaluate((el, checked) => {
    el.checked = checked
    el.dispatchEvent(new Event('change', {bubbles: true}))
  }, Boolean(info.project.use.rtl))
  if (await page.locator('#kit-hide').isVisible()) await page.locator('#kit-hide').click()
  await expect(page.locator('[data-cal-month]')).toBeVisible()
  await settle(page)
}

async function capture(page, info, name) {
  await settle(page)
  await page.locator('.page-content').evaluate(el => el.scrollTo(0, 0))
  await page.screenshot({path: info.outputPath(name), animations: 'disabled'})
}

async function layout(page, value) {
  await page.locator('[data-event-view-menu] summary').click()
  await page.locator(`[data-event-view-select="${value}"]`).click()
  await expect(page.locator('[data-event-layout]')).toHaveAttribute('data-event-layout', value)
}

const row = (page, title) => page.locator('[data-event-entry]').filter({hasText: title})

test('only Calendar and Agenda remain, with an aligned agenda-only sidebar', async ({page}, info) => {
  await page.setViewportSize({width: 1600, height: 1000})
  await go(page, info)
  await expect(page.locator('[data-event-sidebar]')).toHaveCount(0)
  await expect(page.locator('[data-cal-month] [data-date]')).toHaveCount(42)
  const widths = await page.locator('.event-workspace').evaluate(el => [el.clientWidth, el.querySelector('[data-calendar]').clientWidth])
  expect(Math.abs(widths[0] - widths[1])).toBeLessThanOrEqual(1)
  await page.locator('[data-event-view-menu] summary').click()
  await expect(page.locator('[data-event-view-select]')).toHaveCount(2)
  await expect(page.locator('[data-event-view-select="cards"]')).toHaveCount(0)
  await page.locator('[data-event-view-select="agenda"]').click()
  const sidebar = page.locator('[data-event-sidebar]')
  await expect(sidebar).toBeVisible()
  await expect(sidebar.locator(':scope > section')).toHaveCount(2)
  await expect(page.locator('[data-event-selected], [data-event-day-summary], [data-event-card]')).toHaveCount(0)
  const tops = await page.locator('.event-workspace').evaluate(el => [...el.querySelectorAll(':scope > .event-main, :scope > .event-sidebar')].map(child => child.getBoundingClientRect().top))
  expect(Math.abs(tops[0] - tops[1])).toBeLessThanOrEqual(1)
  await capture(page, info, 'events-agenda.png')
  await layout(page, 'calendar')
  await expect(sidebar).toHaveCount(0)
  await capture(page, info, 'events-calendar.png')
})

test('date picker navigates days, months, and years and retains keyboard focus', async ({page}, info) => {
  await page.setViewportSize({width: 1600, height: 1000})
  await go(page, info)
  await layout(page, 'agenda')
  const sidebar = page.locator('[data-event-sidebar]')
  await sidebar.locator('[data-event-day="2026-10-13"]').focus()
  await page.keyboard.press(info.project.use.rtl ? 'ArrowLeft' : 'ArrowRight')
  await expect(sidebar.locator('[data-event-day="2026-10-14"]')).toBeFocused()
  await sidebar.locator('[data-event-day="2026-10-06"]').click()
  await expect(page.locator('[data-cal-modes] [data-value="day"]')).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('[data-agenda-event]')).toHaveCount(1)
  await expect(page.locator('[data-agenda-event]')).toContainText('Company holiday')
  await expect(sidebar.locator('[data-event-day="2026-10-06"]')).toBeFocused()
  await expect(sidebar.locator('[aria-current="date"]')).toHaveAttribute('data-event-day', '2026-10-13')
  await expect(sidebar.locator('[data-event-upcoming]').first()).toContainText('Monthly sales review')
  await sidebar.locator('[data-event-month]').selectOption('11')
  await expect(page.locator('[data-cal-modes] [data-value="month"]')).toHaveAttribute('aria-pressed', 'true')
  await expect(sidebar.locator('[data-event-month]')).toBeFocused()
  await sidebar.locator('[data-event-year]').fill('2027')
  await sidebar.locator('[data-event-year]').press('Tab')
  await expect(page.locator('[data-cal-preset]')).toContainText(info.project.use.rtl ? '٢٠٢٧' : '2027')
  await expect(sidebar.locator('[data-event-year]')).toHaveValue('2027')
  await sidebar.locator('[data-event-mini-shift="-1"]').click()
  await expect(sidebar.locator('[data-event-month]')).toHaveValue('10')
  await expect(sidebar.locator('[data-event-year]')).toHaveValue('2027')
  await sidebar.locator('[data-event-year]').fill('1899')
  await sidebar.locator('[data-event-year]').press('Tab')
  await expect(sidebar.locator('[data-event-year]')).toHaveValue('2027')
})


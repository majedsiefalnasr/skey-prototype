test('Boxed Kanban scrolls through the side gutters after appearance changes and resizing', async ({page}) => {
  await go(page, '/help-screens/notes')
  await page.evaluate(() => {
    const key = 'skey-proto-collab'
    const state = JSON.parse(sessionStorage.getItem(key))
    state.noteColumns = ['draft', 'active', 'review', 'approved', 'reference', 'ideas', 'archived'].map(id => ({id, label: id}))
    sessionStorage.setItem(key, JSON.stringify(state))
  })
  await page.reload()
  const body = page.locator('.notes-view [data-collab-body]')
  const partialColumns = () => body.evaluate(el => {
    const viewport = el.getBoundingClientRect()
    return [...el.querySelectorAll('[data-column]')].filter(column => {
      const rect = column.getBoundingClientRect()
      const visible = Math.min(rect.right, viewport.right) - Math.max(rect.left, viewport.left)
      return visible > 1 && visible < rect.width - 1
    }).length
  })
  for (const width of test.info().project.use.rtl ? [390, 720] : [1440, 2048, 1000]) {
    await page.setViewportSize({width, height: 1000})
    for (const layout of ['fluid', 'boxed']) {
      await body.evaluate(el => { el.scrollLeft = getComputedStyle(el).direction === 'rtl' ? -937 : 937 })
      await page.locator('#content-layout').evaluate((el, value) => { el.value = value; el.dispatchEvent(new Event('change', {bubbles: true})) }, layout)
      if (layout === 'boxed') await expect(page.locator('body')).toHaveClass(/layout-boxed/)
      else await expect(page.locator('body')).not.toHaveClass(/layout-boxed/)
      if (layout === 'fluid') await expect.poll(partialColumns).toBe(0)
      else {
        // The canvas edge is the primary scrollport's padding box: its
        // vertical scrollbar is not part of the board's pass-through area.
        await expect.poll(() => body.evaluate(el => Math.abs(el.getBoundingClientRect().width - el.closest('.page-content').clientWidth))).toBeLessThan(2)
        await expect(body).toHaveCSS('scroll-snap-type', 'none')
        await body.evaluate(el => { el.scrollLeft = getComputedStyle(el).direction === 'rtl' ? -137 : 137 })
        const geometry = await body.evaluate(el => {
          const viewport = el.getBoundingClientRect()
          const scroller = el.closest('.page-content'), rect = scroller.getBoundingClientRect()
          const canvas = {left: rect.left + scroller.clientLeft, right: rect.left + scroller.clientLeft + scroller.clientWidth}
          return {left: Math.abs(viewport.left - canvas.left), right: Math.abs(viewport.right - canvas.right), page: document.documentElement.scrollWidth, window: innerWidth}
        })
        expect(geometry.left).toBeLessThan(2)
        expect(geometry.right).toBeLessThan(2)
        expect(geometry.page).toBeLessThanOrEqual(geometry.window)
      }
      await body.locator('[data-column]').last().scrollIntoViewIfNeeded()
      if (layout === 'fluid') await expect.poll(partialColumns).toBe(0)
      else {
        const fullyReachable = await body.locator('[data-column]').last().evaluate(el => {
          const rect = el.getBoundingClientRect(), viewport = el.closest('[data-collab-body]').getBoundingClientRect()
          return rect.left >= viewport.left - 1 && rect.right <= viewport.right + 1
        })
        expect(fullyReachable).toBe(true)
      }
    }
  }
})


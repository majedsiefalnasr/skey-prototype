async function go(page, path) {
  await page.route('https://cdn.jsdelivr.net/**', route => route.abort())
  await page.goto(path)
  await page.locator('#simulate-loading').evaluate(el => { el.checked = false; el.dispatchEvent(new Event('change', {bubbles: true})) })
  await page.locator('#rtl').evaluate((el, checked) => { el.checked = checked; el.dispatchEvent(new Event('change', {bubbles: true})) }, Boolean(test.info().project.use.rtl))
  if (await page.locator('#kit-hide').isVisible()) await page.locator('#kit-hide').click()
}
